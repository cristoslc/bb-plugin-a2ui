// Generates the typed catalog module and the skill's component index from the
// vendored A2UI Basic Catalog. Run with `npm run catalog:build` after replacing
// catalog/basic.v1.json.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "catalog", "basic.v1.json");
const catalog = JSON.parse(await readFile(source, "utf8"));

const components = catalog.components ?? {};
const functions = catalog.functions ?? {};

// The catalog schema gives several components no top-level description, so
// these one-line summaries are written here, from the Basic Catalog guide.
const DESCRIPTIONS = {
  Text: "Body or caption text. Renders Markdown.",
  Image: "An image from an http or https URL.",
  Icon: "A system icon by name, or an inline SVG path.",
  Video: "A video player.",
  AudioPlayer: "An audio player.",
  Row: "Lays its children out horizontally.",
  Column: "Lays its children out vertically.",
  List: "A vertical or horizontal list of children.",
  Card: "A bordered container around one child.",
  Tabs: "Tabbed panels, each with a title and a child.",
  Modal: "A trigger that opens a content panel.",
  Divider: "A horizontal or vertical rule.",
  Button: "A clickable control around a Text child, with an action.",
  TextField: "A text, number, password or long-text input.",
  CheckBox: "A labelled on/off input.",
  ChoicePicker: "A single-select or multi-select list of options.",
  Slider: "A numeric input between min and max.",
  DateTimeInput: "A date and time input in ISO 8601.",
};

function branches(spec) {
  return [spec, ...(spec?.allOf ?? [])];
}

function description(spec, name) {
  const text = DESCRIPTIONS[name] ?? spec?.description ?? "";
  return text.split(". ")[0].replace(/\s+/g, " ").trim();
}

function propsOf(spec) {
  const names = new Set();
  for (const branch of branches(spec)) {
    for (const key of Object.keys(branch?.properties ?? {})) names.add(key);
    if (branch?.$ref?.includes("Checkable")) names.add("@checks");
  }
  return [...names].filter((name) => name !== "component");
}

function requiredOf(spec) {
  return [...new Set(branches(spec).flatMap((branch) => branch?.required ?? []))];
}

const componentNames = Object.keys(components);
const functionNames = Object.keys(functions);

const module_ = `// Generated by scripts/build-catalog.mjs from catalog/basic.v1.json.
// Do not edit by hand; run \`npm run catalog:build\`.

export interface CatalogComponent {
  readonly description: string;
  readonly required: readonly string[];
  readonly properties: readonly string[];
}

export interface CatalogDocument {
  readonly catalogId: string;
  readonly components: Readonly<Record<string, CatalogComponent>>;
  readonly functions: Readonly<Record<string, { readonly description: string }>>;
}

export const CATALOG_ID = ${JSON.stringify(catalog.catalogId)};

export const CATALOG_COMPONENTS: Readonly<Record<string, CatalogComponent>> = ${JSON.stringify(
  Object.fromEntries(
    componentNames.map((name) => [
      name,
      {
        description: description(components[name], name),
        required: requiredOf(components[name]),
        properties: propsOf(components[name]),
      },
    ]),
  ),
  null,
  2,
)};

export const CATALOG_COMPONENT_NAMES = ${JSON.stringify(componentNames)} as const;
export type CatalogComponentName = (typeof CATALOG_COMPONENT_NAMES)[number];

export const CATALOG_FUNCTIONS: Readonly<Record<string, { readonly description: string }>> = ${JSON.stringify(
  Object.fromEntries(
    functionNames.map((name) => [name, { description: description(functions[name]) }]),
  ),
  null,
  2,
)};

export const CATALOG_FUNCTION_NAMES = ${JSON.stringify(functionNames)} as const;
export type CatalogFunctionName = (typeof CATALOG_FUNCTION_NAMES)[number];
`;

await writeFile(path.join(root, "catalog", "generated.ts"), module_, "utf8");

const rows = componentNames.map((name) => {
  const required = requiredOf(components[name]);
  const properties = propsOf(components[name]);
  const requiredText = required.length === 0 ? "-" : required.map((p) => `\`${p}\``).join(", ");
  const propertyText = properties.length === 0 ? "-" : properties.map((p) => `\`${p}\``).join(", ");
  return `| \`${name}\` | ${requiredText} | ${propertyText} | ${description(components[name], name)} |`;
});

const functionRows = functionNames.map(
  (name) => `| \`${name}\` | ${description(functions[name])} |`,
);

const catalogDoc = `# A2UI v1.0 Basic Catalog

Generated from \`catalog/basic.v1.json\`. Do not edit by hand; run \`npm run catalog:build\`.

Catalog id: \`${catalog.catalogId}\`

## Components

| Component | Required | Other properties | What it does |
| --- | --- | --- | --- |
${rows.join("\n")}

Every component also accepts \`id\`, \`weight\`, \`@checks\` (on input
components), \`@accessibility\`, \`@metadata\`, and \`@catalogId\`.

## Functions

| Function | What it does |
| --- | --- |
${functionRows.join("\n")}
`;

await writeFile(path.join(root, "skills", "a2ui", "CATALOG.md"), catalogDoc, "utf8");

console.log(
  `wrote catalog/generated.ts and skills/a2ui/CATALOG.md (${componentNames.length} components, ${functionNames.length} functions)`,
);
